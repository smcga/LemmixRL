/** which row of a letter is drawn on every row of the line, from the top of a capital down */
const ROWS = [0, 1, 1, 2, 2, 3, 4, 4, 5, 5, 6, 7, 8];
/** the row of the line the top of a capital is on */
const TOP = 2;

export const PIXEL_FONT_HEIGHT = 16;

export interface PixelGlyph {
  code: number;
  width: number;
  /** is there a pixel at (x, y) of the 16 pixel line */
  bit: (x: number, y: number) => boolean;
}

/** The letters as they are drawn: strokes of two pixels, 11 rows for a capital. */
export function pixelGlyphs(): PixelGlyph[] {
  return Object.entries(GLYPHS).map(([ch, rows]) => {
    const lines = ROWS.map((r) => {
      const row = rows[r] ?? '';
      const at = (x: number) => row[x] === '#';
      const out: boolean[] = [];
      for (let x = 0; x <= row.length; x++) {
        // a pixel, or the one left of it made wider (unless that would close a gap of one pixel)
        out.push(at(x) || (x > 0 && at(x - 1) && !at(x + 1)));
      }
      return out;
    });
    const width = Math.max(1, ...lines.map((l) => l.lastIndexOf(true) + 1));
    return { code: ch.charCodeAt(0), width, bit: (x, y) => lines[y - TOP]?.[x] === true };
  });
}
